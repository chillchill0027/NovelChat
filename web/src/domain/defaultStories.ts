export function createStoryFromPreset(
  preset: CharacterPreset,
  customOverride?: { name?: string; age?: number; gender?: string; role?: string; background?: string },
): StoryRecord {
  const now = nowIsoString();
  const id = `story_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;
  const playerName = customOverride?.name?.trim() || preset.player_name;
  const playerClass = customOverride?.role?.trim() || preset.name;
  const world = defaultModernWorldSetting();
  const story: StoryState = {
    current_round: 0,
    active_characters: [],
    current_location: '云桥里老小区',
    time_of_day: '周一早晨',
    weather: '多云',
    mood: '现实压力与新机会并存',
    scene_description: '周一早晨七点半，窗外飘着微凉的云层，手机屏幕上同时亮着三条未读消息：房东陈姐的房租提醒、同事林越的临时顶会求助、以及招聘顾问孟琪发来的高薪面试邀约。',
    pending_events: [
      '本周向房东陈姐交房租',
      '回复同事林越的临时顶会请求',
      '回复招聘顾问孟琪的高薪面试邀请',
    ],
    global_flags: {},
  };
  const player: PlayerState = {
    name: playerName,
    race: '人类',
    age: customOverride?.age ?? 25,
    gender: customOverride?.gender?.trim() || '未明确',
    class: playerClass,
    appearance: '普通城市通勤穿着，随身带着手机、钥匙和交通卡。',
    personality: '由玩家行动逐步塑造',
    background: customOverride?.background?.trim() || preset.description,
    lore: emptyCharacterLore(),
    charm: preset.charm,
    hunting_skill: preset.hunting_skill,
    social_rank: preset.social_rank,
    luck: preset.luck,
    alpha: preset.alpha,
    resistance: preset.resistance,
    cv: preset.cv,
    level: 1,
    skills: [
      { name: '观察', level: 1 },
      { name: '沟通', level: 1 },
      { name: '时间管理', level: 1 },
    ],
    physical_state: defaultPhysicalState(),
    mental_state: defaultMentalState(),
    custom_attributes: {},
    relationships: {},
    inventory: [
      { name: '智能手机', quantity: 1, type: '日用品', description: '装着微信、工作群与账单提醒', origin: '随身携带', acquired_at: '开局' },
      { name: '交通卡', quantity: 1, type: '日用品', description: '海临市地铁公交通用卡', origin: '随身携带', acquired_at: '开局' },
    ],
    quest_log: [],
    story_progress: {
      current_arc: '海临市日常',
      current_chapter: '周一早晨',
      current_scene: '云桥里老小区',
      current_goal: '决定今天三条消息的回复顺序与安排',
    },
  };
  return {
    id,
    title: playerName,
    subtitle: `${world.name} · ${playerClass}`,
    preview: story.scene_description,
    created_at: now,
    updated_at: now,
    world,
    story,
    player,
    characters: defaultModernCharacters(now, playerName),
    worldbook: defaultModernWorldbookEntries(now),
    narratives: [],
    summaries: [],
    chapters: [],
    checkpoints: {},
    narration: defaultNarrationSettings(),
    sync_status: {
      ...defaultSyncStatus(),
      last_suggestions: ['先查看房东陈姐的消息', '问问同事林越会议细节', '看一眼孟琪发来的岗位要求'],
    },
  };
}
